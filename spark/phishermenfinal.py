from pyspark.ml.feature import VectorAssembler
from pyspark.ml.classification import LogisticRegression
from pyspark.ml.evaluation import BinaryClassificationEvaluator

# Choose some numeric features (exclude ID/text columns)
feature_cols = [c for c in numeric_cols if c not in ["label", "LineOfCode"]]  # example

assembler = VectorAssembler(
    inputCols=feature_cols,
    outputCol="features"
)

model_df = assembler.transform(df).select("features", "label")

train, test = model_df.randomSplit([0.8, 0.2], seed=42)

lr = LogisticRegression(featuresCol="features", labelCol="label")
lr_model = lr.fit(train)

pred = lr_model.transform(test)

evaluator = BinaryClassificationEvaluator(labelCol="label", metricName="areaUnderROC")
auc = evaluator.evaluate(pred)
print("Test AUC:", auc)